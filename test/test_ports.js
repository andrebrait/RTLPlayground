/* Duplex changes must retain the speed command they modify when saving. */
const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync('../html/app.js', 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf('var CONF_CMDS = ['), source.indexOf('function setDirty(')), context);
vm.runInContext(source.slice(source.indexOf('var CONF_OVERWRITE = ['), source.indexOf('function writeConfig(')), context);
const plain = x => Array.from(x);
let saved = context.mergeConf(['port 1 100m full', 'port 8 auto'], ['port 1 duplex half']);
assert.deepEqual(plain(saved), ['port 1 100m full', 'port 8 auto', 'port 1 duplex half']);
saved = context.mergeConf(saved, ['port 1 duplex full']);
assert.deepEqual(plain(saved), ['port 1 100m full', 'port 8 auto', 'port 1 duplex full']);
saved = context.mergeConf(saved, ['port 1 auto']);
assert.deepEqual(plain(saved), ['port 8 auto', 'port 1 auto']);
console.log('Port speed/duplex configuration replay order passed');
saved = context.mergeConf(['port 1 100m full', 'port 8 auto'], ['port 1 fc off']);
assert.deepEqual(plain(saved), ['port 1 100m full', 'port 8 auto', 'port 1 fc off']);
saved = context.mergeConf(saved, ['port 1 auto']);
assert.deepEqual(plain(saved), ['port 8 auto', 'port 1 fc off', 'port 1 auto']);
saved = context.mergeConf(saved, ['port 1 fc on']);
assert.deepEqual(plain(saved), ['port 8 auto', 'port 1 auto', 'port 1 fc on']);
console.log('Pause configuration persists independently of the speed');
saved = context.mergeConf(['poe port 2 on', 'poe port 3 on', 'port 8 auto'], ['poe port 2 off']);
assert.deepEqual(plain(saved), ['poe port 3 on', 'port 8 auto', 'poe port 2 off']);
saved = context.mergeConf(saved, ['poe port 2 on']);
assert.deepEqual(plain(saved), ['poe port 3 on', 'port 8 auto', 'poe port 2 on']);
console.log('Per-port PoE settings persist independently of Ethernet configuration');
vm.runInContext(source.slice(source.indexOf('function lldpPoe('), source.indexOf('function lldpLoad(')), context);
assert.equal(context.lldpPoe({poe: 'at', poeClass: 4, poeReq: 255}), '802.3at, class 4, 25.5 W');
assert.equal(context.lldpPoe({poe: 'af', poeClass: null, poeReq: 60}), '802.3af, 6.0 W');
assert.equal(context.lldpPoe({poe: null, poeClass: null, poeReq: null}), '');
console.log('LLDP-reported PD power labels passed');
context.S = {info: {mib_family: 'rtl836x'}};
saved = context.mergeConf(['lag 1 1 3', 'laghash 1 smac', 'lag 2 5 6'], ['lag 1 d']);
assert.deepEqual(plain(saved), ['laghash 1 smac', 'lag 2 5 6']);
saved = context.mergeConf(saved, ['laghash 2 dport']);
assert.deepEqual(plain(saved), ['lag 2 5 6', 'laghash 2 dport']);
saved = context.mergeConf(['lag 1 lacp 1 3', 'lag 2 5 6'], ['lag 1 lacp off']);
assert.deepEqual(plain(saved), ['lag 2 5 6']);
saved = context.mergeConf(saved, ['lag 1 lacp 2 4', 'lag 2 d']);
assert.deepEqual(plain(saved), ['lag 1 lacp 2 4']);
context.S.info.mib_family = 'rtl837x';
saved = context.mergeConf(['lag 1 1 3', 'laghash 1 smac', 'laghash 2 dport'], ['lag 1 d']);
assert.deepEqual(plain(saved), ['laghash 2 dport']);
console.log('Global RTL836x hash survives group deletion; RTL837x hash remains per-group');
vm.runInContext(source.slice(source.indexOf('function bwHex('), source.indexOf('function bwApply(')), context);
context.S.info.mib_family = 'rtl836x';
assert.equal(context.bwHex(0.008), '08');
assert.equal(context.bwHex(0.024), '18');
assert.equal(context.bwHex(1000), '0f4240');
for (const value of [0.007, 0.009, 1000.008, NaN, Infinity]) assert.equal(context.bwHex(value), null);
context.S.info.mib_family = 'rtl837x';
assert.equal(context.bwHex(0.016), '10');
assert.equal(context.bwHex(10000), '989680');
console.log('Native 8-kbit rate boundaries and shared 16-kbit interface passed');
vm.runInContext(source.slice(source.indexOf('function portCmds('), source.indexOf('function ptChanged(')), context);
const unchangedPort = {en: true, name: 'uplink', spd: 'auto', mtu: '', fc: false, eee: false, poe: null};
const clearedName = {...unchangedPort, name: ''};
const clearCommands = context.portCmds({p: {port: 1, enabled: true, isSFP: false}}, clearedName, unchangedPort);
saved = context.mergeConf(['port 1 name uplink', 'port 2 name spare'], plain(clearCommands));
assert.deepEqual(plain(saved).filter(line => /^port [12] name/.test(line)), ['port 2 name spare']);
console.log('Clearing a port name removes its saved override without affecting another port');
