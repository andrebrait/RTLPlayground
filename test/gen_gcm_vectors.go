// gen_gcm_vectors writes the AES-128-GCM test vectors for crypto/aes_gcm.c.
//
//	go run test/gen_gcm_vectors.go
//
// It writes test/gcm_vectors.h (random cases for the host test) and
// crypto/gcm_kat.h (one inform reply from a UniFi Network 10.6 controller,
// used by the host test and by the firmware's `unifi selftest`). Every case
// uses a 16-byte IV and a 40-byte AAD, as UniFi inform packets do. Go's
// crypto/cipher is the reference; the random cases come from a fixed seed, so
// the output only changes when this file does.
package main

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"encoding/hex"
	"fmt"
	"math/rand"
	"os"
	"strings"
)

