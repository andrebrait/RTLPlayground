const defaultKey = "ba86f2bbe107c7c57eb5f2690775c712"

func gcm16(key []byte) cipher.AEAD {
	b, err := aes.NewCipher(key)
	must(err)
	g, err := cipher.NewGCMWithNonceSize(b, 16)
	must(err)
	return g
}

// wrapIV picks an IV whose first counter block ends in ff ff ff xx, with xx
// close enough to ff that the 32-bit counter wraps within the message. The
// counter comes from decrypting the first keystream block with the key.
func wrapIV(key, iv []byte, r *rand.Rand, blocks int) {
	b, err := aes.NewCipher(key)
	must(err)
	g, zero, ctr := gcm16(key), make([]byte, 16), make([]byte, 16)
	for {
		r.Read(iv)
		b.Decrypt(ctr, g.Seal(nil, iv, zero, nil)[:16])
		if ctr[12] == 0xff && ctr[13] == 0xff && ctr[14] == 0xff && int(ctr[15]) > 255-blocks+2 {
			return
		}
	}
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func cArray(w *strings.Builder, b []byte) {
	for i := 0; i < len(b); i += 12 {
		w.WriteString("\t")
		for j := i; j < i+12 && j < len(b); j++ {
			fmt.Fprintf(w, "0x%02x,", b[j])
			if j+1 < i+12 && j+1 < len(b) {
				w.WriteString(" ")
			}
		}
		w.WriteString("\n")
	}
}

func main() {
	pkt, err := hex.DecodeString(katPacket)
	must(err)
	key, _ := hex.DecodeString(defaultKey)
	plain, err := gcm16(key).Open(nil, pkt[16:32], pkt[40:], pkt[:40])
	must(err)
	if !bytes.HasPrefix(plain, []byte(`{"_type":"setparam"`)) {
		panic("unexpected KAT plaintext")
	}

	var k strings.Builder
	k.WriteString("/* Generated by test/gen_gcm_vectors.go. Do not edit. */\n")
	k.WriteString("/* A UniFi controller inform reply under the default key: 40-byte header\n")
	k.WriteString(" * (the AAD, IV at offset 16), ciphertext, then the 16-byte tag. */\n")
	k.WriteString("#define GCM_KAT_PLAIN_LEN " + fmt.Sprint(len(plain)) + "\n")
	k.WriteString("static __code const uint8_t gcm_kat_key[16] = {\n")
	cArray(&k, key)
	k.WriteString("};\nstatic __code const uint8_t gcm_kat_packet[" + fmt.Sprint(len(pkt)) + "] = {\n")
	cArray(&k, pkt)
	k.WriteString("};\n")
	must(os.WriteFile("crypto/gcm_kat.h", []byte(k.String()), 0o644))

	r := rand.New(rand.NewSource(20261121))
	// The last case wraps the 32-bit block counter (see wrapIV).
	lens := []int{0, 1, 15, 16, 17, 31, 32, 33, 100, 378, 10240, 1500}
	var v strings.Builder
	v.WriteString("/* Generated by test/gen_gcm_vectors.go. Do not edit. */\n")
	v.WriteString("static const uint8_t gcm_kat_plain[] = {\n")
	cArray(&v, plain)
	v.WriteString("};\n\nstruct gcm_vec {\n\tuint8_t key[16], iv[16], aad[40], tag[16];\n")
	v.WriteString("\tuint16_t len;\n\tconst uint8_t *pt, *ct;\n};\n\n")
	for i, n := range lens {
		key, iv, aad, pt := make([]byte, 16), make([]byte, 16), make([]byte, 40), make([]byte, n)
		r.Read(key)
		r.Read(iv)
		r.Read(aad)
		r.Read(pt)
		if i == len(lens)-1 {
			wrapIV(key, iv, r, n/16)
		}
		out := gcm16(key).Seal(nil, iv, pt, aad)
		fmt.Fprintf(&v, "static const uint8_t gcm_pt%d[] = {\n", i)
		cArray(&v, append(pt, 0))
		fmt.Fprintf(&v, "};\nstatic const uint8_t gcm_ct%d[] = {\n", i)
		cArray(&v, append(out[:n:n], 0))
		fmt.Fprintf(&v, "};\nstatic const struct gcm_vec gcm_vec%d = {\n\t{\n", i)
		cArray(&v, key)
		v.WriteString("\t}, {\n")
		cArray(&v, iv)
		v.WriteString("\t}, {\n")
		cArray(&v, aad)
		v.WriteString("\t}, {\n")
		cArray(&v, out[n:])
		fmt.Fprintf(&v, "\t}, %d, gcm_pt%d, gcm_ct%d\n};\n\n", n, i, i)
	}
	v.WriteString("static const struct gcm_vec *const gcm_vecs[] = {\n")
	for i := range lens {
		fmt.Fprintf(&v, "\t&gcm_vec%d,\n", i)
	}
	v.WriteString("};\n")
	must(os.WriteFile("test/gcm_vectors.h", []byte(v.String()), 0o644))
}
