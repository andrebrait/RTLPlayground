/* Exercise production counter decoding without a browser or hardware. */
const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync('../html/app.js', 'utf8');
const context = vm.createContext({ S: { info: {} } });
vm.runInContext(source.slice(source.indexOf('var MIB = ['), source.indexOf('var ctrPoll = null;')), context);
let raw = Array(55).fill('0x0');
raw[0] = '0x123456789abcdef0';
raw[8] = '0x11223344aabbccdd';
let rows = context.decodeCounters(raw);
assert.equal(rows[0][1], 0x123456789abcdef0n);
assert.equal(rows.find(r => r[0] === 'Interface out discards')[1], 0x11223344n);
assert.equal(rows.find(r => r[0] === '802.1d Tp Port in discards')[1], 0xaabbccddn);
context.S.info.mib_family = 'rtl837x';
assert.equal(context.decodeCounters(raw)[0][1], 0x123456789abcdef0n);
context.S.info.mib_family = 'rtl836x';
raw = Array(58).fill('0x0');
raw[0] = '0x123456789abcdef0';
raw[1] = '0x11223344';
raw[2] = null;
raw[28] = '0x100000001';
raw[57] = '0x89abcdef';
rows = context.decodeCounters(raw);
assert.equal(rows.length, 58);
assert.equal(rows[0][0], 'Interface in Octets');
assert.equal(rows[0][1], 0x123456789abcdef0n);
assert.equal(rows[1][0], '802.3 FCS errors');
assert.equal(rows[1][1], 0x11223344n);
assert.equal(rows[2][1], null);
assert.equal(rows[28][0], 'Interface out Octets');
assert.equal(rows[28][1], 0x100000001n);
assert.equal(rows[57][0], 'In known multicast Pkts');
assert.equal(rows[57][1], 0x89abcdefn);
assert(!rows.some(r => r[0].includes('Queue')));
assert.throws(() => context.decodeCounters([]));
vm.runInContext(source.slice(source.indexOf('function counterText('), source.indexOf('function portLabel(')), context);
assert.equal(context.counterText(null), '-');
assert.equal(context.counterText('0x100000001'), '4294967297');
assert.equal(context.counterRate(null, '0x1', 2.5), null);
assert.equal(context.counterRate('0x2', null, 2.5), null);
assert.equal(context.counterRate('0x1', '0x2', 2.5), null);
assert.equal(context.counterRate('0x100000006', '0x100000001', 2.5), 2);
console.log('MIB frontend decoding, labels, unavailable values and deltas passed');
context.LANG = { en: { st_txb: 'TX bad' } };
context.rtlLang = 'en';
vm.runInContext(source.slice(source.indexOf('function t(k, v)'), source.indexOf('function i18nApply()')), context);
assert.equal(context.t('st_txb'), 'TX excessive collisions');
assert.equal(context.t('d_rxbad'), 'RX FCS errors');
assert.equal(context.t('st_txg'), 'TX U/M/B packets');
delete context.S.info.mib_family;
assert.equal(context.t('st_txb'), 'TX bad');
